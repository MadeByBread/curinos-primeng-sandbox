/**
 * Remaps PrimeNG 7's built-in PrimeIcons onto the Phosphor webfont.
 *
 * PrimeNG 7 hardcodes `pi pi-*` classes in its component templates — dropdown
 * triggers, the MultiSelect filter, sort indicators, paginator arrows and so on.
 * Most are not exposed as inputs, so the only way to reach them is CSS.
 *
 * Codepoints are read out of @phosphor-icons/web rather than copied by hand,
 * because they are opaque and a silently wrong one renders as a plausible but
 * incorrect glyph. A Phosphor name that no longer exists fails the build here.
 *
 * Only mapped icons are touched: the generated rules set `font-family` per
 * icon rather than on `.pi` as a whole, so anything left unmapped keeps
 * rendering in PrimeIcons instead of turning into tofu.
 *
 * Reads:  node_modules/@phosphor-icons/web/src/regular/style.css
 * Writes: src/styles/icons/_primeicons.generated.scss
 *
 * Usage: npm run icons:build
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const PHOSPHOR_CSS = path.join(ROOT, 'node_modules/@phosphor-icons/web/src/regular/style.css');
const OUTPUT_PATH = path.join(ROOT, 'src/styles/icons/_primeicons.generated.scss');

/**
 * PrimeIcon name -> Phosphor name.
 *
 * PrimeIcons distinguishes `angle-*` (thin) from `chevron-*` (thick) from
 * `caret-*` (solid triangle). Phosphor's regular weight has one chevron form,
 * so all three collapse onto `caret-*`.
 *
 * Deliberately unmapped, and therefore still PrimeIcons:
 *   star, star-o — Phosphor's filled star lives in the fill weight, which this
 *     app does not load, so Rating would lose its filled/empty distinction.
 *   fw, spin — layout and animation modifiers, not glyphs.
 */
const ICON_MAP = {
  'angle-double-down': 'caret-double-down',
  'angle-double-left': 'caret-double-left',
  'angle-double-right': 'caret-double-right',
  'angle-double-up': 'caret-double-up',
  'angle-down': 'caret-down',
  'angle-left': 'caret-left',
  'angle-right': 'caret-right',
  'angle-up': 'caret-up',
  'arrow-circle-left': 'arrow-circle-left',
  'arrow-circle-right': 'arrow-circle-right',
  'arrow-down': 'arrow-down',
  'arrow-up': 'arrow-up',
  'ban': 'prohibit',
  'bars': 'list',
  'calendar': 'calendar-blank',
  'caret-down': 'caret-down',
  'caret-left': 'caret-left',
  'caret-right': 'caret-right',
  'caret-up': 'caret-up',
  'check': 'check',
  'chevron-down': 'caret-down',
  'chevron-left': 'caret-left',
  'chevron-right': 'caret-right',
  'chevron-up': 'caret-up',
  'circle-off': 'circle',
  'circle-on': 'dot',
  'exclamation-triangle': 'warning',
  'home': 'house',
  'info-circle': 'info',
  'minus': 'minus',
  'plus': 'plus',
  'search': 'magnifying-glass',
  'sort': 'arrows-down-up',
  'sort-down': 'sort-descending',
  'sort-up': 'sort-ascending',
  'spinner': 'circle-notch',
  'step-backward': 'caret-line-left',
  'step-forward': 'caret-line-right',
  'th-large': 'squares-four',
  'times': 'x',
  'upload': 'upload-simple',
  'window-maximize': 'corners-out',
  'window-minimize': 'corners-in'
};

const SCOPE = 'body:not(.primeng-default)';

function readCodepoints(css) {
  const codepoints = {};
  const re = /^\.ph\.ph-([a-z0-9-]+):before\s*\{\s*content:\s*"(\\[0-9a-fA-F]+)"/gm;
  let match;
  while ((match = re.exec(css)) !== null) {
    codepoints[match[1]] = match[2];
  }
  return codepoints;
}

function main() {
  const css = fs.readFileSync(PHOSPHOR_CSS, 'utf8');
  const codepoints = readCodepoints(css);

  const names = Object.keys(ICON_MAP).sort();
  const missing = names.filter(name => !(ICON_MAP[name] in codepoints));
  if (missing.length) {
    throw new Error(
      `Phosphor glyphs not found in the regular webfont: ` +
        missing.map(name => `${ICON_MAP[name]} (for pi-${name})`).join(', ')
    );
  }

  const lines = [
    '// Generated by scripts/primeicons-to-phosphor.js — do not edit by hand',
    '// Re-run: npm run icons:build',
    '//',
    '// Swaps PrimeNG 7\'s hardcoded PrimeIcons for Phosphor glyphs. Scoped to',
    '// Curinos mode, so the stock previews keep their original icons.',
    '',
    names.map(name => `${SCOPE} .pi-${name}::before`).join(',\n') + ' {',
    "  font-family: 'Phosphor' !important;",
    '  font-style: normal;',
    '  font-weight: normal;',
    '  font-variant: normal;',
    '  text-transform: none;',
    '  line-height: 1;',
    '  speak: none;',
    '  -webkit-font-smoothing: antialiased;',
    '  -moz-osx-font-smoothing: grayscale;',
    '}',
    ''
  ];

  names.forEach(name => {
    const phosphor = ICON_MAP[name];
    lines.push(
      `${SCOPE} .pi-${name}::before { content: '${codepoints[phosphor]}'; } // ph-${phosphor}`
    );
  });

  lines.push('');
  fs.writeFileSync(OUTPUT_PATH, lines.join('\n'));
  console.log(`Wrote ${path.relative(ROOT, OUTPUT_PATH)} (${names.length} icons remapped to Phosphor)`);
}

main();
